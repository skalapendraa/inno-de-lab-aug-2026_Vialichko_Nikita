# Используем цикл для проверки правильности ввода
while True:
    length = int(input("Введите длину прямоугольника: "))
    width = int(input("Введите ширину прямоугольника: "))

    # Проверяем, чтобы стороны были больше нуля
    if length > 0 and width > 0:
        break  # Если данные корректны, идем дальше
    else:
        print("Ошибка: Длина и ширина должны быть положительными числами. Попробуйте снова!\n")

# Вычисляем площадь
area = length * width

# Проверяем на равенство сторон и выводим соответствующий результат
if length == width:
    print(f"Площадь квадрата: {area}")
else:
    print(f"Площадь прямоугольника: {area}")